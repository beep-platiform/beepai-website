type I18nValue = { locale: Locale; setLocale: (locale: Locale) => void; t: (key: string) => string };
const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => {
    if (typeof window === "undefined") return "rw";
    const saved = window.localStorage.getItem("beep-locale");
    return saved === "en" || saved === "fr" ? saved : "rw";
  });
  const setLocale = (next: Locale) => setLocaleState(next);
  useEffect(() => {
    window.localStorage.setItem("beep-locale", locale);
    document.documentElement.lang = locale === "rw" ? "rw" : locale;
  }, [locale]);
  const value = useMemo(() => ({ locale, setLocale, t: (key: string) => copy[locale][key] ?? copy.en[key] ?? key }), [locale]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside I18nProvider");
  return value;
}
